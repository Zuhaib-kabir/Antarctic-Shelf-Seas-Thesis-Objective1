def read_seawise_ohc_csv(path):
    dataframe = pd.read_csv(path)
    lower_columns = {column.lower(): column for column in dataframe.columns}

    # Support the long format: month, sea, OHC_0_100m.
    if {"month", "sea"}.issubset(lower_columns):
        month_column = lower_columns["month"]
        sea_column = lower_columns["sea"]
        value_candidates = [
            column
            for column in dataframe.columns
            if "ohc" in column.lower() and "count" not in column.lower()
        ]
        if not value_candidates:
            raise ValueError(f"No OHC value column found in {path}")
        dataframe[month_column] = pd.to_datetime(dataframe[month_column])
        dataframe = dataframe.pivot_table(
            index=month_column,
            columns=sea_column,
            values=value_candidates[0],
            aggfunc="mean",
        )
    else:
        # Support the wide Fig. 5 cache with the first column named time/month.
        time_candidates = [
            column
            for column in dataframe.columns
            if column.lower() in {"time", "month", "date", "unnamed: 0"}
        ]
        time_column = time_candidates[0] if time_candidates else dataframe.columns[0]
        dataframe[time_column] = pd.to_datetime(dataframe[time_column])
        dataframe = dataframe.set_index(time_column)

    dataframe.index = month_start_index(dataframe.index)
    dataframe.columns = [str(column).upper() for column in dataframe.columns]

    for code in SEA_CODES:
        if code not in dataframe.columns:
            dataframe[code] = np.nan

    full_index = pd.date_range(
        f"{START_YEAR}-01-01", f"{END_YEAR}-12-01", freq="MS"
    )
    dataframe = dataframe.reindex(index=full_index, columns=SEA_CODES)
    dataframe.index.name = "time"
    return dataframe.apply(pd.to_numeric, errors="coerce")


