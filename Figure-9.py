def calculate_profile_ohc(p_raw, t_raw, sp_raw, latitude, longitude, gsw_module):
    valid = (
        np.isfinite(p_raw)
        & np.isfinite(t_raw)
        & np.isfinite(sp_raw)
        & (p_raw >= 0.0)
        & (p_raw <= 130.0)
        & (t_raw > -3.0)
        & (t_raw < 20.0)
        & (sp_raw > 20.0)
        & (sp_raw < 42.0)
    )
    if valid.sum() < MIN_VALID_LEVELS_OHC:
        return np.nan

    pressure = np.asarray(p_raw[valid], dtype=float)
    temperature = np.asarray(t_raw[valid], dtype=float)
    salinity = np.asarray(sp_raw[valid], dtype=float)

    order = np.argsort(pressure)
    pressure = pressure[order]
    temperature = temperature[order]
    salinity = salinity[order]

    pressure, unique_indices = np.unique(pressure, return_index=True)
    temperature = temperature[unique_indices]
    salinity = salinity[unique_indices]

    if len(pressure) < MIN_VALID_LEVELS_OHC:
        return np.nan
    if pressure.min() > MAX_SHALLOWEST_VALID_DBAR:
        return np.nan
    if pressure.max() < MIN_DEEPEST_VALID_DBAR:
        return np.nan

    temperature_grid = np.interp(OHC_GRID_DBAR, pressure, temperature)
    salinity_grid = np.interp(OHC_GRID_DBAR, pressure, salinity)

    try:
        absolute_salinity = gsw_module.SA_from_SP(
            salinity_grid, OHC_GRID_DBAR, longitude, latitude
        )
        conservative_temperature = gsw_module.CT_from_t(
            absolute_salinity, temperature_grid, OHC_GRID_DBAR
        )
        freezing_temperature = gsw_module.CT_freezing(
            absolute_salinity, OHC_GRID_DBAR, 0.0
        )
        density = gsw_module.rho(
            absolute_salinity, conservative_temperature, OHC_GRID_DBAR
        )
        depth = -gsw_module.z_from_p(OHC_GRID_DBAR, latitude)
    except Exception:
        return np.nan

    temperature_excess = np.maximum(
        conservative_temperature - freezing_temperature, 0.0
    )
    heat_density = density * CP0 * temperature_excess

    if hasattr(np, "trapezoid"):
        ohc_j_m2 = np.trapezoid(heat_density, depth)
    else:
        ohc_j_m2 = np.trapz(heat_density, depth)

    if not np.isfinite(ohc_j_m2) or ohc_j_m2 < 0.0:
        return np.nan
    return ohc_j_m2 / 1.0e9  # GJ m-2


def build_seawise_ohc_from_raw_argo():
    """Slow fallback used only when neither existing OHC cache is available."""
    if not ARGO_PROFILE_FILE.exists():
        raise FileNotFoundError(
            "No sea-wise OHC CSV, no gridded OHC cache, and no raw Argo file "
            f"were found. Last path checked: {ARGO_PROFILE_FILE}"
        )

    try:
        import gsw
        from netCDF4 import Dataset
    except ImportError as error:
        raise ImportError(
            "Raw Argo OHC construction requires gsw and netCDF4. In Colab run: "
            "%pip install -q gsw netCDF4"
        ) from error

    print("\nNo OHC cache found; building sea-wise OHC from raw Argo profiles.")
