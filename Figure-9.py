def open_dataset_robust(path, chunks=None):
    if not Path(path).exists():
        raise FileNotFoundError(f"Input file not found: {path}")

    try:
        return xr.open_dataset(
            path,
            decode_times=True,
            decode_timedelta=False,
            chunks=chunks or {},
        )
    except ImportError as error:
        message = str(error).lower()
        if "dask" not in message and "chunk manager" not in message:
            raise
        print(f"WARNING: Dask unavailable; opening {Path(path).name} without chunks.")
        return xr.open_dataset(
            path,
            decode_times=True,
            decode_timedelta=False,
            chunks=None,
        )


def standardize_dataset(dataset):
    rename = {}
    aliases = {
        "valid_time": "time",
        "time_counter": "time",
        "month": "time",
        "latitude": "lat",
        "nav_lat": "lat",
        "longitude": "lon",
        "nav_lon": "lon",
    }

    available = set(dataset.coords) | set(dataset.dims)
    for old_name, new_name in aliases.items():
        if old_name in available and new_name not in available:
            rename[old_name] = new_name

    if rename:
        dataset = dataset.rename(rename)

    required = {"time", "lat", "lon"}
    missing = required.difference(dataset.coords)
    if missing:
        raise ValueError(f"Missing required coordinates: {sorted(missing)}")

    if dataset["lat"].ndim != 1 or dataset["lon"].ndim != 1:
        raise ValueError("This code requires one-dimensional lat/lon coordinates.")

    dataset = dataset.drop_vars(["number", "expver"], errors="ignore")

    if float(dataset["lon"].max()) > 180.0:
        dataset = dataset.assign_coords(
            lon=((dataset["lon"] + 180.0) % 360.0) - 180.0
        )

    dataset = dataset.sortby("lon").sortby("lat").sortby("time")
    dataset = dataset.sel(
        time=slice(f"{START_YEAR}-01-01", f"{END_YEAR}-12-31")
    )
    return dataset.where(dataset["lat"] <= -60.0, drop=True)


def find_variable(dataset, candidates, descriptive_name):
    for candidate in candidates:
        if candidate in dataset.data_vars:
            return candidate

    lower_lookup = {name.lower(): name for name in dataset.data_vars}
    for candidate in candidates:
        if candidate.lower() in lower_lookup:
            return lower_lookup[candidate.lower()]

    raise ValueError(
        f"Could not find {descriptive_name}. Tried {candidates}. "
        f"Available variables: {list(dataset.data_vars)}"
    )


def resolve_current_input_path(path):
    """Accept current filenames with/without a space and uo/vo north suffix."""
    path = Path(path)
