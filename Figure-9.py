# 7. AUTOCORRELATION-AWARE LAG TESTS AND FDR

def lag_one_autocorrelation(values, dates):
    """Lag-1 correlation using only observations exactly one month apart."""
    values = np.asarray(values, dtype=float)
    dates = pd.DatetimeIndex(dates)

    if len(values) < 4:
        return 0.0, 0

    month_number = dates.year * 12 + dates.month
    adjacent = np.diff(month_number) == 1
    first = values[:-1][adjacent]
    second = values[1:][adjacent]
    valid = np.isfinite(first) & np.isfinite(second)
    first = first[valid]
    second = second[valid]

    if len(first) < 4 or np.nanstd(first) == 0.0 or np.nanstd(second) == 0.0:
        return 0.0, int(len(first))

    correlation = float(np.corrcoef(first, second)[0, 1])
    if not np.isfinite(correlation):
        correlation = 0.0
    return float(np.clip(correlation, -0.99, 0.99)), int(len(first))


def effective_sample_size(number, rho_sic, rho_driver):
    """Bretherton-style effective N using the product of lag-1 correlations."""
    product = float(np.clip(rho_sic * rho_driver, -0.99, 0.99))
    estimate = number * (1.0 - product) / (1.0 + product)
    return float(np.clip(estimate, 3.0, float(number)))


def autocorrelation_adjusted_p_value(correlation, effective_n):
    if not np.isfinite(correlation) or effective_n <= 2.0:
        return np.nan

    clipped_r = float(np.clip(correlation, -0.999999, 0.999999))
    statistic = clipped_r * np.sqrt(
        (effective_n - 2.0) / max(1.0e-12, 1.0 - clipped_r**2)
    )
    return float(2.0 * student_t.sf(abs(statistic), df=effective_n - 2.0))


def calculate_one_lag(sic_series, driver_series, lag):
    """Calculate corr[SIC(t), driver(t + lag)] for one sector and lag."""
    shifted_driver = driver_series.copy()
    shifted_driver.index = shifted_driver.index - pd.DateOffset(months=int(lag))

    paired = pd.concat(
        [sic_series.rename("SIC"), shifted_driver.rename("driver")], axis=1
    ).dropna()
    paired = paired.sort_index()
    number = len(paired)

    if number < MIN_VALID_PAIRS:
        return {
            "r": np.nan,
            "p_autocorr": np.nan,
            "n": number,
            "n_eff": np.nan,
            "rho1_sic": np.nan,
            "rho1_driver": np.nan,
            "adjacent_pairs_sic": 0,
            "adjacent_pairs_driver": 0,
        }

    x = paired["SIC"].values.astype(float)
    y = paired["driver"].values.astype(float)
    if np.nanstd(x) == 0.0 or np.nanstd(y) == 0.0:
        return {
            "r": np.nan,
            "p_autocorr": np.nan,
            "n": number,
            "n_eff": np.nan,
            "rho1_sic": np.nan,
            "rho1_driver": np.nan,
            "adjacent_pairs_sic": 0,
            "adjacent_pairs_driver": 0,
        }

    correlation = float(pearsonr(x, y).statistic)
    rho_sic, adjacent_sic = lag_one_autocorrelation(x, paired.index)
    rho_driver, adjacent_driver = lag_one_autocorrelation(y, paired.index)
    n_eff = effective_sample_size(number, rho_sic, rho_driver)
    p_value = autocorrelation_adjusted_p_value(correlation, n_eff)

    return {
        "r": correlation,
        "p_autocorr": p_value,
        "n": number,
        "n_eff": n_eff,
        "rho1_sic": rho_sic,
        "rho1_driver": rho_driver,
        "adjacent_pairs_sic": adjacent_sic,
        "adjacent_pairs_driver": adjacent_driver,
    }


def benjamini_hochberg(p_values):
    """Return BH-adjusted q-values in the original input shape."""
    p_values = np.asarray(p_values, dtype=float)
    q_values = np.full(p_values.shape, np.nan, dtype=float)
    valid_indices = np.flatnonzero(np.isfinite(p_values))

    if len(valid_indices) == 0:
        return q_values

    valid_p = p_values[valid_indices]
    order = np.argsort(valid_p)
    sorted_p = valid_p[order]
    number_tests = len(sorted_p)

    adjusted_sorted = sorted_p * number_tests / np.arange(1, number_tests + 1)
    adjusted_sorted = np.minimum.accumulate(adjusted_sorted[::-1])[::-1]
    adjusted_sorted = np.clip(adjusted_sorted, 0.0, 1.0)

    adjusted_valid = np.empty(number_tests, dtype=float)
    adjusted_valid[order] = adjusted_sorted
    q_values[valid_indices] = adjusted_valid
    return q_values


def calculate_driver_panel(sic_anomalies, driver_anomalies, driver_label):
    rows = []

    for sector in SEA_CODES:
        for lag in LAGS:
            statistics = calculate_one_lag(
                sic_anomalies[sector], driver_anomalies[sector], int(lag)
            )
            rows.append(
                {
                    "Driver": driver_label,
                    "Sector": sector,
                    "Sector_name": SEA_NAMES[sector],
                    "Lag_months": int(lag),
                    **statistics,
                }
            )

    result = pd.DataFrame(rows)
    result["q_fdr"] = benjamini_hochberg(result["p_autocorr"].values)
    result["significant_fdr"] = result["q_fdr"] < FDR_ALPHA
    return result



